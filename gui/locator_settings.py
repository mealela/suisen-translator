from PySide6.QtWidgets import (QCheckBox, QComboBox, QDoubleSpinBox,
                               QFormLayout, QGroupBox, QLabel, QSpinBox,
                               QVBoxLayout, QWidget)

from config import AppConfig

_D = AppConfig()        # 默认值唯一来源, 不再在界面里另抄一份


def _hint(text):
    label = QLabel(text)
    label.setProperty("hint", True)
    label.setWordWrap(True)
    return label


def _tip(widget, text):
    widget.setToolTip(text)
    return widget


class LocatorSettingsWidget(QWidget):
    def __init__(self, cfg, parent=None):
        super().__init__(parent)
        self.cfg = cfg
        root = QVBoxLayout(self)

        general = QGroupBox("字幕定位(RapidOCR · ONNX Runtime)")
        form = QFormLayout(general)
        self.cmb_version = QComboBox()
        self.cmb_version.addItem("PP-OCRv5(稳定, 推荐)", "PP-OCRv5")
        self.cmb_version.addItem("PP-OCRv6(需 rapidocr ≥ 3.9, 不支持时自动退回 v5)", "PP-OCRv6")
        self._set_data(self.cmb_version, getattr(cfg, "locator_rapid_version", _D.locator_rapid_version))
        form.addRow("检测模型版本:", self.cmb_version)
        self.cmb_type = QComboBox()
        self.cmb_type.addItem("server / medium: 精度优先(推荐)", "server")
        self.cmb_type.addItem("mobile / small: 速度优先", "mobile")
        self._set_data(self.cmb_type, getattr(cfg, "locator_rapid_type", _D.locator_rapid_type))
        form.addRow("检测模型规格:", self.cmb_type)
        self.chk_dml = QCheckBox("DirectML 显卡加速(需 pip install onnxruntime-directml; 未安装时自动忽略)")
        self.chk_dml.setChecked(bool(getattr(cfg, "locator_rapid_dml", _D.locator_rapid_dml)))
        form.addRow("", self.chk_dml)
        self.sp_threads = QSpinBox()
        self.sp_threads.setRange(0, 64)
        self.sp_threads.setSpecialValueText("自动(核数-2)")
        self.sp_threads.setValue(int(getattr(cfg, "locator_threads", _D.locator_threads)))
        _tip(self.sp_threads, "检测/识别使用的 CPU 线程数。默认留 2 个核给界面与解码。")
        form.addRow("推理线程数:", self.sp_threads)
        self.sp_side = QSpinBox()
        self.sp_side.setRange(640, 2560)
        self.sp_side.setSingleStep(64)
        self.sp_side.setValue(int(getattr(cfg, "locator_det_limit_side_len", _D.locator_det_limit_side_len)))
        _tip(self.sp_side, "检测前把画面最长边缩到此值。1080p 字幕 ≥20px 时 1280 足够; 调大更慢。")
        form.addRow("检测缩放边长:", self.sp_side)
        self.sp_interval = QDoubleSpinBox()
        self.sp_interval.setRange(0.10, 2.0)
        self.sp_interval.setSingleStep(0.05)
        self.sp_interval.setDecimals(2)
        self.sp_interval.setSuffix(" 秒")
        self.sp_interval.setValue(float(getattr(cfg, "sample_interval", _D.sample_interval)))
        _tip(self.sp_interval, "每隔多久截一帧做检测。调小不易漏短字幕但更慢; 调大更快。")
        form.addRow("采样间隔:", self.sp_interval)
        self.chk_precise = QCheckBox("逐帧确认字幕起止(更准, 稍慢)")
        self.chk_precise.setChecked(bool(getattr(cfg, "precise_timing", _D.precise_timing)))
        form.addRow("", self.chk_precise)
        self.chk_flash = QCheckBox("闪现字幕探针(场景切换时立即补检)")
        self.chk_flash.setChecked(bool(getattr(cfg, "locator_flash_probe", _D.locator_flash_probe)))
        form.addRow("", self.chk_flash)
        self.sp_min_dur = QDoubleSpinBox()
        self.sp_min_dur.setRange(0.08, 3.0)
        self.sp_min_dur.setSingleStep(0.05)
        self.sp_min_dur.setDecimals(2)
        self.sp_min_dur.setSuffix(" 秒")
        self.sp_min_dur.setValue(float(getattr(cfg, "min_seg_dur", _D.min_seg_dur)))
        _tip(self.sp_min_dur, "短于该时长的轨迹当噪声丢弃。")
        form.addRow("候选最短时长:", self.sp_min_dur)
        self.sp_hits = QSpinBox()
        self.sp_hits.setRange(1, 10)
        self.sp_hits.setValue(int(getattr(cfg, "locator_min_hits", _D.locator_min_hits)))
        _tip(self.sp_hits, "一条字幕至少要被检测器认出几次; 设为 1 = 关闭该过滤。")
        form.addRow("最少命中次数:", self.sp_hits)
        self.sp_conf = QDoubleSpinBox()
        self.sp_conf.setRange(0.05, 0.95)
        self.sp_conf.setSingleStep(0.05)
        self.sp_conf.setDecimals(2)
        self.sp_conf.setValue(float(getattr(cfg, "locator_min_conf", _D.locator_min_conf)))
        _tip(self.sp_conf, "低于该置信度的检测框直接忽略。误框多 → 调高; 漏字幕 → 调低。")
        form.addRow("单帧最低置信度:", self.sp_conf)
        self.sp_minh = QDoubleSpinBox()
        self.sp_minh.setRange(0.3, 5.0)
        self.sp_minh.setSingleStep(0.1)
        self.sp_minh.setDecimals(1)
        self.sp_minh.setSuffix(" %")
        self.sp_minh.setValue(float(getattr(cfg, "locator_min_height_ratio", _D.locator_min_height_ratio)) * 100)
        _tip(self.sp_minh, "检测框短边(字高/列宽)小于画面高度的该百分比 → 视为细线/噪点。1080p 下 1.0% ≈ 11px。")
        form.addRow("最小字高:", self.sp_minh)
        self.sp_max = QSpinBox()
        self.sp_max.setRange(2, 64)
        self.sp_max.setValue(int(getattr(cfg, "locator_max_frame_candidates", _D.locator_max_frame_candidates)))
        form.addRow("每帧候选上限:", self.sp_max)
        self.sp_bridge = QDoubleSpinBox()
        self.sp_bridge.setRange(0.3, 3.0)
        self.sp_bridge.setSingleStep(0.1)
        self.sp_bridge.setDecimals(2)
        self.sp_bridge.setSuffix(" 秒")
        self.sp_bridge.setValue(float(getattr(cfg, "seg_bridge_gap", _D.seg_bridge_gap)))
        _tip(self.sp_bridge, "同一句字幕闪断后, 间隔在此窗口内会自动接回同一条。")
        form.addRow("同句续接窗口:", self.sp_bridge)
        self.sp_evgap = QDoubleSpinBox()
        self.sp_evgap.setRange(0.5, 4.0)
        self.sp_evgap.setSingleStep(0.1)
        self.sp_evgap.setDecimals(2)
        self.sp_evgap.setSuffix(" 秒")
        self.sp_evgap.setValue(float(getattr(cfg, "event_merge_gap", _D.event_merge_gap)))
        _tip(self.sp_evgap, "识别完成后, 内容相同且间隔小于该值的相邻字幕会合并为一条。")
        form.addRow("同文合并间隔:", self.sp_evgap)
        root.addWidget(general)

        verify = QGroupBox("智能核验(自动区分字幕与水印/招牌等)")
        vf = QFormLayout(verify)
        self.chk_vlm = QCheckBox("用 AI 视觉模型核验可疑候选")
        self.chk_vlm.setChecked(bool(getattr(cfg, "locator_vlm_verify", _D.locator_vlm_verify)))
        _tip(self.chk_vlm, "对拿不准的候选截图问通用 VLM 确认。GLM-OCR 这类纯 OCR 模型不能判别, 会自动跳过。")
        vf.addRow("", self.chk_vlm)
        self.cmb_verify = QComboBox()
        self.cmb_verify.addItem("关闭", "off")
        self.cmb_verify.addItem("只核验可疑候选(推荐)", "ambiguous")
        self.cmb_verify.addItem("核验全部候选(质量优先, 调用多)", "all")
        self._set_data(self.cmb_verify, getattr(cfg, "locator_verify_mode", _D.locator_verify_mode))
        vf.addRow("核验范围:", self.cmb_verify)
        self.sp_budget = QSpinBox()
        self.sp_budget.setRange(0, 5000)
        self.sp_budget.setValue(int(getattr(cfg, "locator_verify_budget", _D.locator_verify_budget)))
        vf.addRow("每视频核验上限:", self.sp_budget)
        self.sp_vthr = QDoubleSpinBox()
        self.sp_vthr.setRange(0.50, 0.99)
        self.sp_vthr.setSingleStep(0.01)
        self.sp_vthr.setDecimals(2)
        self.sp_vthr.setValue(float(getattr(cfg, "locator_verify_threshold", _D.locator_verify_threshold)))
        _tip(self.sp_vthr, "AI 判定'不是字幕'时需要达到的把握度才真正剔除。")
        vf.addRow("剔除把握门槛:", self.sp_vthr)
        root.addWidget(verify)

        quality = QGroupBox("质量过滤(会删除候选; 被剔除的候选在画面上以红框标出原因)")
        qf = QFormLayout(quality)
        self.chk_symbol = QCheckBox("丢弃纯符号/标点(♥ … !!)")
        self.chk_symbol.setChecked(bool(getattr(cfg, "filter_symbol_only", _D.filter_symbol_only)))
        qf.addRow("", self.chk_symbol)
        self.chk_llm = QCheckBox("AI 语义过滤: 剔除效果音/拟声词特效字/水印/UI/招牌(使用翻译模型)")
        self.chk_llm.setChecked(bool(getattr(cfg, "filter_llm", _D.filter_llm)))
        _tip(self.chk_llm, "想保留拟声词就关掉它, 或在[提示词]里调整判定规则。")
        qf.addRow("", self.chk_llm)
        self.sp_static = QDoubleSpinBox()
        self.sp_static.setRange(0, 600)
        self.sp_static.setDecimals(0)
        self.sp_static.setSuffix(" 秒")
        self.sp_static.setSpecialValueText("不限制")
        self.sp_static.setValue(float(getattr(cfg, "static_text_max_dur", _D.static_text_max_dur)))
        _tip(self.sp_static, "同一处文字静止超过该时长 → 判为台标/水印。长时间不换的字幕请调大或设为 0。")
        qf.addRow("静止文字判台标:", self.sp_static)
        root.addWidget(quality)

        root.addWidget(_hint("提示: 定位框决定译文的位置、字号与擦除/遮罩范围。候选过多 → 提高置信度/最小字高/最少命中; "
                             "漏字幕 → 反向调。"))
        root.addStretch(1)

    def _set_data(self, combo, value):
        for i in range(combo.count()):
            if combo.itemData(i) == value:
                combo.setCurrentIndex(i)
                return

    def apply(self, cfg):
        cfg.locator_rapid_version = self.cmb_version.currentData()
        cfg.locator_rapid_type = self.cmb_type.currentData()
        cfg.locator_rapid_dml = self.chk_dml.isChecked()
        cfg.locator_threads = self.sp_threads.value()
        cfg.locator_det_limit_side_len = self.sp_side.value()
        cfg.sample_interval = round(self.sp_interval.value(), 2)
        cfg.precise_timing = self.chk_precise.isChecked()
        cfg.locator_flash_probe = self.chk_flash.isChecked()
        cfg.min_seg_dur = round(self.sp_min_dur.value(), 2)
        cfg.locator_min_hits = self.sp_hits.value()
        cfg.locator_min_conf = round(self.sp_conf.value(), 2)
        cfg.locator_min_height_ratio = round(self.sp_minh.value() / 100.0, 4)
        cfg.locator_max_frame_candidates = self.sp_max.value()
        cfg.seg_bridge_gap = round(self.sp_bridge.value(), 2)
        cfg.event_merge_gap = round(self.sp_evgap.value(), 2)
        cfg.locator_vlm_verify = self.chk_vlm.isChecked()
        cfg.locator_verify_mode = self.cmb_verify.currentData()
        cfg.locator_verify_budget = self.sp_budget.value()
        cfg.locator_verify_threshold = round(self.sp_vthr.value(), 2)
        cfg.filter_symbol_only = self.chk_symbol.isChecked()
        cfg.filter_llm = self.chk_llm.isChecked()
        cfg.static_text_max_dur = float(self.sp_static.value())
